"""
app/models.py – SQLAlchemy ORM models.

Models:
    User    – application users with role-based access control
    Sensor  – physical sensor devices with configurable thresholds
    Reading – individual sensor measurements
    Alert   – safety / maintenance alerts generated by the rules engine
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Optional

from flask_login import UserMixin
from werkzeug.security import check_password_hash, generate_password_hash

from app import db, login_manager


def utc_now() -> datetime:
    """Return a naive datetime representing the current UTC time."""
    return datetime.now(timezone.utc).replace(tzinfo=None)


# ── User ──────────────────────────────────────────────────────────────────────

class User(UserMixin, db.Model):
    """
    Application user.

    Roles:
        admin    – full access; manage sensors and users
        engineer – can acknowledge and resolve alerts
        viewer   – read-only access
    """

    __tablename__ = "users"
    __allow_unmapped__ = True

    id: int = db.Column(db.Integer, primary_key=True)
    username: str = db.Column(db.String(64), unique=True, nullable=False, index=True)
    email: str = db.Column(db.String(120), unique=True, nullable=False)
    password_hash: str = db.Column(db.String(256), nullable=False)
    role: str = db.Column(
        db.Enum("admin", "engineer", "viewer", name="user_role"),
        nullable=False,
        default="viewer",
    )
    is_active: bool = db.Column(db.Boolean, default=True, nullable=False)
    must_change_password: bool = db.Column(db.Boolean, default=False, nullable=False)
    created_at: datetime = db.Column(db.DateTime, default=utc_now)

    def set_password(self, password: str) -> None:
        """Hash and store a new password."""
        self.password_hash = generate_password_hash(password)

    def check_password(self, password: str) -> bool:
        """Return True if *password* matches the stored hash."""
        return check_password_hash(self.password_hash, password)

    def has_role(self, *roles: str) -> bool:
        """Return True if the user's role is one of *roles*."""
        return self.role in roles

    def __repr__(self) -> str:
        return f"<User {self.username!r} role={self.role!r}>"


@login_manager.user_loader
def load_user(user_id: str) -> Optional[User]:
    """Flask-Login callback: load user by primary key."""
    user = db.session.get(User, int(user_id))
    return user if user is not None and user.is_active else None


# ── Sensor ────────────────────────────────────────────────────────────────────

class Sensor(db.Model):
    """
    Physical sensor device.

    Threshold semantics:
        warning_min / warning_max  – yellow badge; creates a warning alert
        critical_min / critical_max – red badge; creates a critical alert
        None means the limit is not applicable (e.g. gas sensor has no minimum)
    """

    __tablename__ = "sensors"
    __allow_unmapped__ = True

    id: int = db.Column(db.Integer, primary_key=True)
    name: str = db.Column(db.String(120), unique=True, nullable=False)
    type: str = db.Column(
        db.Enum(
            "temperature", "pressure", "humidity", "gas", "vibration",
            name="sensor_type",
        ),
        nullable=False,
    )
    location: str = db.Column(db.String(120), nullable=False)
    unit: str = db.Column(db.String(20), nullable=False)

    # Thresholds (nullable – use None to disable that side)
    warning_min: Optional[float] = db.Column(db.Float, nullable=True)
    warning_max: Optional[float] = db.Column(db.Float, nullable=True)
    critical_min: Optional[float] = db.Column(db.Float, nullable=True)
    critical_max: Optional[float] = db.Column(db.Float, nullable=True)

    is_active: bool = db.Column(db.Boolean, default=True, nullable=False)
    created_at: datetime = db.Column(db.DateTime, default=utc_now)

    # Relationships
    readings = db.relationship(
        "Reading", backref="sensor", lazy="dynamic", cascade="all, delete-orphan"
    )
    alerts = db.relationship(
        "Alert", backref="sensor", lazy="dynamic", cascade="all, delete-orphan"
    )

    def latest_reading(self) -> Optional["Reading"]:
        """Return the most recent Reading for this sensor, or None."""
        return (
            self.readings.order_by(
                Reading.timestamp.desc(), Reading.id.desc()
            ).first()
        )

    def status(self) -> str:
        """
        Return the current status string based on the latest reading.

        Returns:
            'normal' | 'warning' | 'critical' | 'no_data'
        """
        reading = self.latest_reading()
        if reading is None:
            return "no_data"
        from app.rules import check_threshold
        return check_threshold(self, reading.value)

    def to_dict(self) -> dict:
        """Serialise to JSON-safe dictionary."""
        lr = self.latest_reading()
        return {
            "id": self.id,
            "name": self.name,
            "type": self.type,
            "location": self.location,
            "unit": self.unit,
            "warning_min": self.warning_min,
            "warning_max": self.warning_max,
            "critical_min": self.critical_min,
            "critical_max": self.critical_max,
            "is_active": self.is_active,
            "latest_value": lr.value if lr else None,
            "latest_timestamp": lr.timestamp.isoformat() if lr else None,
            "status": self.status(),
        }

    def __repr__(self) -> str:
        return f"<Sensor {self.name!r} type={self.type!r}>"


# ── Reading ───────────────────────────────────────────────────────────────────

class Reading(db.Model):
    """A single sensor measurement."""

    __tablename__ = "readings"
    __allow_unmapped__ = True

    id: int = db.Column(db.Integer, primary_key=True)
    sensor_id: int = db.Column(
        db.Integer, db.ForeignKey("sensors.id"), nullable=False, index=True
    )
    value: float = db.Column(db.Float, nullable=False)
    timestamp: datetime = db.Column(
        db.DateTime, default=utc_now, nullable=False, index=True
    )

    # Back-reference to alerts generated from this reading
    alerts = db.relationship("Alert", backref="reading", lazy="dynamic")

    def to_dict(self) -> dict:
        """Serialise to JSON-safe dictionary."""
        return {
            "id": self.id,
            "sensor_id": self.sensor_id,
            "value": self.value,
            "timestamp": self.timestamp.isoformat(),
        }

    def __repr__(self) -> str:
        return f"<Reading sensor={self.sensor_id} value={self.value} ts={self.timestamp}>"


# ── Alert ─────────────────────────────────────────────────────────────────────

class Alert(db.Model):
    """
    Safety or predictive-maintenance alert.

    Severity:
        warning  – value crossed a warning threshold
        critical – value crossed a critical threshold
        drift    – slow, gradual drift detected (predictive maintenance)

    Status lifecycle:
        open → acknowledged → resolved
    """

    __tablename__ = "alerts"
    __allow_unmapped__ = True

    id: int = db.Column(db.Integer, primary_key=True)
    sensor_id: int = db.Column(
        db.Integer, db.ForeignKey("sensors.id"), nullable=False, index=True
    )
    reading_id: Optional[int] = db.Column(
        db.Integer, db.ForeignKey("readings.id"), nullable=True
    )

    severity: str = db.Column(
        db.Enum("warning", "critical", "drift", name="alert_severity"),
        nullable=False,
    )
    message: str = db.Column(db.String(512), nullable=False)
    status: str = db.Column(
        db.Enum("open", "acknowledged", "resolved", name="alert_status"),
        nullable=False,
        default="open",
        index=True,
    )

    created_at: datetime = db.Column(db.DateTime, default=utc_now)

    # Who acted on the alert
    acknowledged_by: Optional[int] = db.Column(
        db.Integer, db.ForeignKey("users.id"), nullable=True
    )
    resolved_by: Optional[int] = db.Column(
        db.Integer, db.ForeignKey("users.id"), nullable=True
    )
    resolved_at: Optional[datetime] = db.Column(db.DateTime, nullable=True)

    # Relationships to users
    acknowledged_by_user = db.relationship(
        "User", foreign_keys=[acknowledged_by], backref="acknowledged_alerts"
    )
    resolved_by_user = db.relationship(
        "User", foreign_keys=[resolved_by], backref="resolved_alerts"
    )

    def to_dict(self) -> dict:
        """Serialise to JSON-safe dictionary."""
        return {
            "id": self.id,
            "sensor_id": self.sensor_id,
            "reading_id": self.reading_id,
            "severity": self.severity,
            "message": self.message,
            "status": self.status,
            "created_at": self.created_at.isoformat(),
            "acknowledged_by": self.acknowledged_by,
            "resolved_by": self.resolved_by,
            "resolved_at": self.resolved_at.isoformat() if self.resolved_at else None,
        }

    def __repr__(self) -> str:
        return (
            f"<Alert sensor={self.sensor_id} severity={self.severity!r} "
            f"status={self.status!r}>"
        )
